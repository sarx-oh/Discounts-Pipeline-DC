"""Export an authorized Databricks source tree into a fresh local directory.

Read-only remotely. Native notebooks are exported as SOURCE; regular files as
AUTO. The generated ZIP is built from the downloaded bytes, never from a local
working copy. Private runtime folders and unknown objects cause rejection.
Requires the official Databricks CLI and an authenticated profile.
"""
import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import subprocess
import sys
from validate_release import PRIVATE_NAMES, PRIVATE_PARTS, validate

ROOT_DIRS = {'configs', 'resources', 'src', 'tools', 'tests', 'docs', 'evidence', 'notebooks'}
ROOT_FILES = {'README.md', '.gitignore', 'requirements-analysis.txt', 'SHA256.json'}


def export(remote, destination, profile):
    """Return object metadata and hashes; reject a nonempty destination."""
    if destination.exists():
        raise ValueError('Destination must not exist; choose a fresh export directory')
    remote = remote.rstrip('/')
    if not remote.startswith('/Users/') or remote in {'/Users'}:
        raise ValueError('Use an explicit project source folder under /Users/')
    def cli(*args):
        result = subprocess.run(['databricks', *args, '--profile', profile, '--output', 'json'],
                                capture_output=True, text=True, check=True)
        return json.loads(result.stdout) if result.stdout.strip() else {}
    objects = []
    def walk(path):
        listing = cli('workspace', 'list', path)
        entries = listing if isinstance(listing, list) else listing.get('objects', [])
        for obj in entries:
            rel = PurePosixPath(obj['path']).relative_to(remote)
            if '..' in rel.parts or PRIVATE_PARTS.intersection(rel.parts):
                # Interpreter caches are generated by notebook imports, not release source.
                if '__pycache__' in rel.parts:
                    continue
                raise ValueError(f'Private runtime path in source tree: {rel}')
            if rel.parts[0] not in ROOT_DIRS and str(rel) not in ROOT_FILES:
                raise ValueError(f'Unexpected source path: {rel}')
            if rel.name in PRIVATE_NAMES:
                raise ValueError(f'Private file in source tree: {rel}')
            if obj['object_type'] == 'DIRECTORY':
                walk(obj['path'])
            elif obj['object_type'] in {'FILE', 'NOTEBOOK'}:
                objects.append((str(rel), obj))
            else:
                raise ValueError(f'Unsupported workspace object: {rel}')
    walk(remote)
    destination.mkdir(parents=True)
    files, inventory = {}, []
    for name, obj in sorted(objects):
        target = destination / name
        target.parent.mkdir(parents=True, exist_ok=True)
        fmt = 'SOURCE' if obj['object_type'] == 'NOTEBOOK' else 'AUTO'
        cli('workspace', 'export', obj['path'], '--format', fmt, '--file', str(target))
        files[name] = target.read_bytes()
        if len(files[name]) > 2_000_000:
            raise ValueError(f'Unexpectedly large source file: {name}')
        inventory.append({'path':name, 'object_type':obj['object_type'], 'format':fmt,
                          'sha256':hashlib.sha256(files[name]).hexdigest()})
    if findings := validate(files):
        raise ValueError('Export validation failed: '+repr(findings))
    return {'remote_source':remote, 'files':inventory, 'source_validation':'PASS'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--remote-root', required=True)
    parser.add_argument('--destination', type=Path, required=True)
    parser.add_argument('--profile', required=True)
    parser.add_argument('--archive', type=Path, required=True)
    parser.add_argument('--report', type=Path, required=True)
    args = parser.parse_args()
    report = export(args.remote_root, args.destination, args.profile)
    # Use this reviewed packager; root discovery belongs to the exported copy.
    subprocess.run([sys.executable, str(args.destination/'tools/package.py'),
                    '--output', str(args.archive.resolve())], check=True)
    subprocess.run([sys.executable, str(args.destination/'tools/validate_release.py'),
                    '--archive', str(args.archive.resolve())], check=True)
    report['archive_sha256'] = hashlib.sha256(args.archive.read_bytes()).hexdigest()
    report['archive'] = str(args.archive.resolve())
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2)+'\n')
    print(json.dumps({'status':'PASS', 'exported_files':len(report['files']),
                      'archive':report['archive'], 'report':str(args.report)}))


if __name__ == '__main__':
    main()
